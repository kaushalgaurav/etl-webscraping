"""Gemini data: one prompt in, values stored in Gemini's own tables.

A table from Gemini is model output, labelled as such:

* Everything lands in Gemini's own tables (store.py) — never in the census/HMIS
  warehouse, the datasets table or dashboard_master.
* Each fetch records what it is: prompt, model, the sources Gemini named per
  column and the pages search grounding used, and which columns it called
  estimates.
* A one-source fetch (census / hmis) uses that source's own warehouse column
  names, and can fetch all of them in batches, combined into one table.
"""
import io
import json
import re
import threading
from concurrent.futures import ThreadPoolExecutor
from datetime import timedelta

import pandas as pd
from sqlalchemy import inspect, text

from app.constants import district_crosswalk as crosswalk
from app.db.session import engine
from app.helpers.dataframe import snake_case
from app.modules.ai_data import gemini, store

WARNING = ("AI-generated by Google Gemini. Not an official dataset: values may be "
           "misremembered or estimated. Use only after checking against the named sources.")

# Wide views / exports pivot at most this many source+indicator columns.
MAX_WIDE_COLUMNS = 500

# One source per fetch, its value columns named exactly as in that source's own
# warehouse master table — so gemini_master columns line up with census_master /
# hmis_master. The list is read live from the table (read only), so it follows
# the warehouse as it changes.
SINGLE_SOURCES = {
    "census": {"name": "Census", "table": "census_master",
               "label": "Census of India 2011, Primary Census Abstract (PCA), district level"},
    "hmis": {"name": "HMIS", "table": "hmis_master",
             "label": "HMIS (Health Management Information System, MoHFW) Standard Reports, "
                      "F.1 Performance of Key HMIS Indicators, district level"},
}
# Geography, time and bookkeeping columns of those tables — not indicators.
_NOT_INDICATORS = {
    "_dataset_id", "_ingested_at", "survey_id", "level", "state", "state_name", "district",
    "district_name", "state_id", "district_id", "unique_id", "subdistrict", "town_village",
    "tv_seq_no", "urbrur", "is_duplicate_area", "report_type", "report_year", "period",
    "parent_area", "source_file", "area", "metric_year", "name",
}


def source_columns(source: str) -> list[str]:
    """The indicator column names of a source's warehouse master table."""
    table = SINGLE_SOURCES[source]["table"]
    with engine.connect() as conn:
        if not inspect(conn).has_table(table):
            return []
        names = [c["name"] for c in inspect(conn).get_columns(table)]
    return sorted(n for n in names if n not in _NOT_INDICATORS)


def restrict_to_source(table: dict, source: str, allowed: list[str]) -> tuple[dict, list[str]]:
    """Keep place/time columns and the source's own column names; drop the rest.

    Returns (table, rejected column names). Every kept value column is
    attributed to the one source, whatever Gemini wrote in column_sources.
    """
    allowed_set = set(allowed)
    place = {c for c in store._place_columns(table["columns"]).values() if c}
    keep = [i for i, c in enumerate(table["columns"])
            if c in place or snake_case(c) in allowed_set]
    rejected = [c for i, c in enumerate(table["columns"]) if i not in keep]
    columns = [snake_case(table["columns"][i]) if table["columns"][i] not in place
               else table["columns"][i] for i in keep]
    name = SINGLE_SOURCES[source]["name"]
    units = {snake_case(k): (v or {}).get("unit")
             for k, v in (table.get("column_sources") or {}).items()}
    return ({**table, "columns": columns,
             "rows": [[row[i] if i < len(row) else None for i in keep] for row in table["rows"]],
             "sources": [{"name": name}],
             "column_sources": {c: {"source": name, "unit": units.get(c)}
                                for c in columns if c not in place},
             "estimated_columns": [snake_case(c) for c in table.get("estimated_columns") or []]},
            rejected)


def to_frame(table: dict) -> pd.DataFrame:
    """Gemini's columns/rows as a DataFrame, numbers made numeric."""
    columns = [str(c) for c in table["columns"]]
    rows = [list(r)[:len(columns)] + [None] * (len(columns) - len(r)) for r in table["rows"]]
    df = pd.DataFrame(rows, columns=columns)
    for col in df.columns:
        cleaned = df[col].map(lambda v: re.sub(r"[,%+\s]", "", v) if isinstance(v, str) else v)
        numeric = pd.to_numeric(cleaned, errors="coerce")
        # Convert only when the column is essentially numeric, so a name
        # column with one stray number stays text.
        if numeric.notna().sum() >= max(1, int(0.8 * df[col].notna().sum())):
            df[col] = numeric
    return df


# --------------------------------------------------------------------------
# Fetch -> raw -> clean -> master
# --------------------------------------------------------------------------

# Gemini takes 30-90 s per table, so a fetch runs in the background on this
# module's own small pool (not the census/HMIS job system). Two workers: the
# free tier allows only a few calls a minute anyway.
_executor = ThreadPoolExecutor(max_workers=2, thread_name_prefix="gemini")
# clean/master are rebuilt per survey by delete + insert; two fetches finishing
# together must not interleave those, or a survey's rows would be doubled.
_build_lock = threading.Lock()
# A fetch still "running" this long after it started was lost to a restart.
_STALE_AFTER = timedelta(minutes=15)


def start_fetch(prompt: str, survey_id: int, use_search: bool,
                source: str | None = None, max_columns: int = 30,
                all_columns: bool = False, columns: list[str] | None = None,
                years: list[str] | None = None) -> dict:
    """Plan the Gemini calls, record the request, hand it to a worker. Returns at once.

    The work is split into units — one per (year, column batch):
      * `years`       one unit set per year, every row stamped with that year;
      * `columns`     exactly these columns of the source, in batches;
      * `all_columns` every column of the source, in batches;
      * otherwise     one call per year in which Gemini picks the columns.
    """
    if (all_columns or columns) and not source:
        raise ValueError("all_columns / columns need a source (census or hmis): they name "
                         "that source's warehouse columns.")
    allowed = source_columns(source) if source else None
    if source and not allowed:
        raise ValueError(f"{SINGLE_SOURCES[source]['table']} has no columns yet — build the "
                         f"{source} warehouse first, so Gemini can use its column names.")
    if columns:
        unknown = [c for c in columns if c not in set(allowed)]
        if unknown:
            raise ValueError(f"Not {source} warehouse columns: {', '.join(unknown[:20])}. "
                             f"See GET /ai-data/columns?source={source}.")
    wanted = columns or (allowed if all_columns else None)
    batches = ([wanted[i:i + max_columns] for i in range(0, len(wanted), max_columns)]
               if wanted else [None])
    units = [(year, batch) for year in (years or [None]) for batch in batches]

    fetch_id = store.new_fetch_id()
    with engine.begin() as conn:
        store.ensure_tables(conn)
        conn.execute(text(f"""INSERT INTO {store.FETCHES}
            (id, survey_id, prompt, use_search, status, progress, created_at)
            VALUES (:id, :s, :p, :u, 'running', :pr, :at)"""),
            {"id": fetch_id, "s": survey_id, "p": prompt, "u": use_search,
             "pr": f"call 0/{len(units)}", "at": store.now()})
    _executor.submit(_run_fetch, fetch_id, prompt, survey_id, use_search, source, allowed,
                     max_columns, units)
    return {"fetch_id": fetch_id, "survey_id": survey_id, "status": "running",
            "source": source, "allowed_columns": len(allowed) if allowed else None,
            "years": years, "columns_requested": len(wanted) if wanted else None,
            "gemini_calls": len(units)}


def _progress(fetch_id: str, message: str) -> None:
    with engine.begin() as conn:
        conn.execute(text(f"UPDATE {store.FETCHES} SET progress = :m WHERE id = :f"),
                     {"m": message, "f": fetch_id})


def _run_fetch(fetch_id: str, prompt: str, survey_id: int, use_search: bool,
               source: str | None, allowed: list[str] | None, max_columns: int,
               units: list[tuple[str | None, list[str] | None]]) -> None:
    """Worker: run every unit, store the combined table, mark the fetch done. Never raises."""
    try:
        table = _fetch_units(fetch_id, prompt, use_search, source, allowed, max_columns, units)
        if not table.get("rows"):
            raise gemini.GeminiError("Gemini returned an empty table.")
        _progress(fetch_id, "storing")
        _save_values(fetch_id, table, survey_id)
    except Exception as exc:  # recorded on the fetch row for the caller to read
        with engine.begin() as conn:
            conn.execute(text(f"UPDATE {store.FETCHES} SET status = 'failed', error = :e, "
                              f"finished_at = :at WHERE id = :f"),
                         {"e": str(exc)[:2000], "at": store.now(), "f": fetch_id})


_PLACE_ROLES = ("State", "District", "Year")


def _unit_frame(table: dict, year: str | None) -> pd.DataFrame:
    """One answer's table: place/time columns renamed State / District / Year,
    the requested year stamped on every row (Gemini's own Year is overridden)."""
    df = to_frame(table)
    roles = store._place_columns(df.columns)
    df = df.rename(columns={col: role.title() for role, col in roles.items() if col})
    if year is not None:
        df["Year"] = year
    return df


def _join_key(df: pd.DataFrame) -> pd.Series:
    """Place (+ year) as one comparable key, so 'Purbi' / 'Purba Champaran' meet."""
    parts = []
    for col in _PLACE_ROLES:
        if col in df.columns:
            values = df[col].astype(str)
            parts.append(values if col == "Year" else values.map(crosswalk.normalise))
    return pd.Series(["|".join(p) for p in zip(*parts)], index=df.index) if parts \
        else pd.Series(range(len(df)), index=df.index).astype(str)


def _splittable(exc: Exception) -> bool:
    """An answer too long or cut off — halving the batch is likely to fix it."""
    text_ = str(exc).lower()
    return any(s in text_ for s in ("not valid json", "did not return a json", "max_tokens",
                                    "no answer", "truncat"))


def _fetch_units(fetch_id: str, prompt: str, use_search: bool, source: str | None,
                 allowed: list[str] | None, max_columns: int,
                 units: list[tuple[str | None, list[str] | None]]) -> dict:
    """Run every (year, column batch) unit and combine the answers into one table.

    Rows from all units are matched on place + year, names compared loosely, and
    each column takes the value from whichever unit supplied it. An answer that
    comes back cut off is retried as two half-size batches; any other failed
    unit is recorded in the notes and the rest are kept.
    """
    label = SINGLE_SOURCES[source]["label"] if source else None
    name = SINGLE_SOURCES[source]["name"] if source else None
    queue = list(units)
    frames, notes, rejected, grounding = [], [], [], []
    column_sources: dict = {}
    estimated: set = set()
    model, done = None, 0
    while queue:
        year, batch = queue.pop(0)
        done += 1
        what = f"{len(batch)} columns" if batch else "Gemini picks columns"
        _progress(fetch_id, f"call {done}/{done + len(queue)}"
                            f"{f' — year {year}' if year else ''} ({what})")
        extra = ""
        if source:
            extra += gemini.vocabulary_instruction(
                label, batch or allowed, len(batch) if batch else max_columns, exact=bool(batch))
        if year:
            extra += gemini.year_instruction(year)
        try:
            answer = gemini.ask_for_table(prompt, use_search=use_search, extra=extra)
        except gemini.GeminiError as exc:
            if batch and len(batch) > 1 and _splittable(exc):
                half = len(batch) // 2
                queue[:0] = [(year, batch[:half]), (year, batch[half:])]
                notes.append(f"A {len(batch)}-column answer{f' for {year}' if year else ''} "
                             "came back cut off; retried as two halves.")
                continue
            notes.append(f"Call{f' for {year}' if year else ''} ({what}) failed: {exc}")
            continue
        if source:
            answer, dropped = restrict_to_source(answer, source, batch or allowed)
            rejected += dropped
        grounding += answer.get("grounding_sources") or []
        column_sources |= answer.get("column_sources") or {}
        estimated |= set(answer.get("estimated_columns") or [])
        model = answer.get("model") or model
        if answer.get("notes"):
            notes.append(f"{year + ': ' if year else ''}{answer['notes']}")
        frame = _unit_frame(answer, year)
        frame["_key"] = _join_key(frame)
        frames.append(frame.drop_duplicates("_key", keep="last"))
    if not frames:
        raise gemini.GeminiError("Every Gemini call failed: " + " | ".join(notes))

    # Each column from whichever unit supplied it (first non-empty value per place+year).
    combined = pd.concat(frames, ignore_index=True).groupby("_key", sort=False).first()
    place = [c for c in _PLACE_ROLES if c in combined.columns]
    values = [c for c in combined.columns if c not in place]
    if allowed:
        order = {c: i for i, c in enumerate(allowed)}
        values.sort(key=lambda c: order.get(c, len(order)))
    combined = combined[place + values]
    years = list(dict.fromkeys(y for y, _ in units if y))
    return {
        "title": (f"{name}: {len(values)} columns" if name else "Gemini table")
                 + (f", years {', '.join(years)}" if years else "") + f" — {prompt[:80]}",
        "columns": list(combined.columns),
        "rows": json.loads(combined.to_json(orient="values")),
        "sources": [{"name": name}] if name else [],
        "column_sources": column_sources,
        "estimated_columns": sorted(estimated),
        "grounding_sources": grounding, "model": model,
        "notes": " ".join(notes) or None,
        "restriction": ({"source": source, "allowed_columns": len(allowed or []),
                         "columns_returned": len(values), "gemini_calls": done,
                         "years": years or None,
                         "rejected_columns": rejected} if source else None),
    }


def _save_values(fetch_id: str, table: dict, survey_id: int) -> None:
    """Store one Gemini answer and rebuild the survey's clean/master rows."""
    df = to_frame(table)
    fetched_at = store.now()
    raw = store.to_raw(df, table, fetch_id, survey_id, fetched_at)
    provenance = {
        "source": "Google Gemini (AI-generated)", "model": table.get("model"),
        "estimated_columns": table.get("estimated_columns") or [],
        "column_sources": table.get("column_sources") or {},
        "model_sources": table.get("sources") or [],
        "grounding_sources": table.get("grounding_sources") or [],
        "notes": table.get("notes"), "warning": WARNING,
        # One-source fetches: which source, and any column Gemini named that is
        # not one of that source's warehouse columns (discarded, not stored).
        "restriction": table.get("restriction"),
    }
    with _build_lock, engine.begin() as conn:
        if not raw.empty:
            raw.to_sql(store.RAW, conn, if_exists="append", index=False)
        built = store.build(conn, survey_id)
        result = {"preview": json.loads(df.head(20).to_json(orient="records")),
                  "survey_now": built}
        conn.execute(text(f"""UPDATE {store.FETCHES} SET
            status = 'succeeded', progress = 'done', title = :t, model = :m, rows_returned = :r, values_stored = :v,
            columns = CAST(:c AS JSONB), sources = CAST(:src AS JSONB),
            provenance = CAST(:prov AS JSONB), result = CAST(:res AS JSONB), finished_at = :at
            WHERE id = :id"""), {
            "id": fetch_id, "t": table.get("title"), "m": table.get("model"),
            "r": int(len(df)),
            "v": int(raw["value_raw"].notna().sum()) if not raw.empty else 0,
            "c": json.dumps(list(df.columns)),
            "src": json.dumps(sorted({r for r in raw.get("source_name", pd.Series()).dropna()})),
            "prov": json.dumps(provenance, default=str),
            "res": json.dumps(result, default=str), "at": store.now()})


def _with_status(row: dict) -> dict:
    """A 'running' fetch older than _STALE_AFTER was lost to a server restart."""
    if (row.get("status") == "running" and row.get("created_at")
            and store.now() - row["created_at"] > _STALE_AFTER):
        row = dict(row) | {"status": "failed",
                           "error": "Interrupted: the server restarted while this fetch ran."}
    return row


def rebuild(survey_id: int) -> dict:
    with _build_lock, engine.begin() as conn:
        store.ensure_tables(conn)
        return store.build(conn, survey_id)


def delete_fetch(fetch_id: str) -> dict | None:
    """Remove one fetch's values everywhere and rebuild its survey."""
    with _build_lock, engine.begin() as conn:
        store.ensure_tables(conn)
        survey = conn.execute(text(f"SELECT survey_id FROM {store.FETCHES} WHERE id = :f"),
                              {"f": fetch_id}).scalar()
        if survey is None:
            return None
        removed = conn.execute(text(f"DELETE FROM {store.RAW} WHERE fetch_id = :f"),
                               {"f": fetch_id}).rowcount
        conn.execute(text(f"DELETE FROM {store.FETCHES} WHERE id = :f"), {"f": fetch_id})
        return {"fetch_id": fetch_id, "survey_id": survey, "values_removed": int(removed or 0),
                "rebuilt": store.build(conn, survey)}


def list_fetches(survey_id: int | None) -> list[dict]:
    with engine.begin() as conn:
        store.ensure_tables(conn)
        sql = (f"SELECT id, survey_id, status, error, prompt, title, model, rows_returned, "
               f"values_stored, sources, progress, created_at, "
               f"finished_at FROM {store.FETCHES}")
        params = {}
        if survey_id is not None:
            sql += " WHERE survey_id = :s"
            params["s"] = survey_id
        rows = conn.execute(text(sql + " ORDER BY created_at DESC"), params).mappings().all()
    return [_with_status(dict(r)) for r in rows]


def get_fetch(fetch_id: str) -> dict | None:
    with engine.begin() as conn:
        store.ensure_tables(conn)
        row = conn.execute(text(f"SELECT * FROM {store.FETCHES} WHERE id = :f"),
                           {"f": fetch_id}).mappings().first()
    return _with_status(dict(row)) if row else None


