def _original_table(fetch_id: str) -> pd.DataFrame:
    """A fetch's table rebuilt in the shape Gemini returned it, from gemini_raw."""
    with engine.connect() as conn:
        raw = pd.read_sql_query(text(f"SELECT * FROM {store.RAW} WHERE fetch_id = :f"),
                                conn, params={"f": fetch_id})
    if raw.empty:
        return raw
    index = ["row_no", "place_level", "state", "district", "year"]
    raw[index] = raw[index].astype(object).where(raw[index].notna(), "")
    out = raw.pivot_table(index=index, columns="column_name", values="value_raw",
                          aggfunc="last").reset_index()
    out.columns.name = None
    return out.drop(columns=["row_no"]).replace("", None).dropna(axis=1, how="all")


def _about_rows(fetch: dict) -> list[tuple[str, str]]:
    p = fetch.get("provenance") or {}
    if isinstance(p, str):
        p = json.loads(p)
    restriction = p.get("restriction") or {}
    rows = [("Warning", WARNING), ("Prompt", fetch.get("prompt")), ("Survey", fetch.get("survey_id")),
            ("Model", p.get("model")), ("Fetched", str(fetch.get("created_at"))),
            ("Source", restriction.get("source") or "free-form"),
            ("Estimated columns", ", ".join(p.get("estimated_columns") or []) or "none declared"),
            ("Notes", p.get("notes"))]
    for col, info in (p.get("column_sources") or {}).items():
        rows.append(("Column source", f"{col}: {info.get('source')} ({info.get('unit') or 'unit n/a'})"))
    for s in p.get("grounding_sources") or []:
        rows.append(("Search result used", f"{s.get('title')} {s.get('url') or ''}".strip()))
    return rows


def _file(sheets: dict[str, pd.DataFrame], fmt: str, stem: str) -> tuple[bytes, str, str]:
    if fmt == "csv":
        first = next(iter(sheets.values()))
        return first.to_csv(index=False).encode("utf-8-sig"), "text/csv", f"{stem}.csv"
    buffer = io.BytesIO()
    with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
        for name, frame in sheets.items():
            # Excel stores no timezone: write fetch times as UTC, zone dropped.
            frame = frame.copy()
            for col in frame.columns:
                if isinstance(frame[col].dtype, pd.DatetimeTZDtype):
                    frame[col] = frame[col].dt.tz_convert("UTC").dt.tz_localize(None)
            frame.to_excel(writer, sheet_name=name[:31], index=False)
    return (buffer.getvalue(),
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", f"{stem}.xlsx")


def export_fetch(fetch: dict, fmt: str) -> tuple[bytes, str, str]:
    """One fetch, in the shape Gemini returned it (+ an 'About' sheet in Excel)."""
    stem = re.sub(r"[^A-Za-z0-9]+", "_", fetch.get("title") or "gemini").strip("_")[:60]
    sheets = {"Data": _original_table(fetch["id"]),
              "About": pd.DataFrame(_about_rows(fetch), columns=["Item", "Detail"])}
    return _file(sheets, fmt, f"{stem}_{fetch['id']}")


def export_survey(survey_id: int, fmt: str, shape: str, filters: dict) -> tuple[bytes, str, str]:
    """A survey's master values, long (one row per value) or wide (one column per indicator)."""
    with engine.begin() as conn:
        store.ensure_tables(conn)
        if shape == "wide":
            # The same table GET /ai-data/warehouse/rows?layer=gemini_master serves.
            data = store.warehouse_frame(conn, store.MASTER, survey_id)
        else:
            _, data = store.read(conn, store.MASTER, survey_id, filters)
        catalogue = store.indicators(conn, survey_id)
    sheets = {"Data": data, "Indicators": catalogue,
              "About": pd.DataFrame([("Warning", WARNING), ("Survey", survey_id),
                                     ("Shape", shape)], columns=["Item", "Detail"])}
    return _file(sheets, fmt, f"gemini_survey_{survey_id}_{shape}")
